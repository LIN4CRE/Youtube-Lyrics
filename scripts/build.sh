#!/usr/bin/env bash
# Builds dist/YoutubeLyrics.exe.
#
# Runs on Linux (or macOS) using Zig's bundled MinGW-w64 toolchain + resource
# compiler, so no Windows machine and no Visual Studio are needed.
#   - Linux/macOS: ZIG=/path/to/zig PYTHON=/path/to/python ./scripts/build.sh
#   - Windows:     build.ps1 (see README) or the same command with zig on PATH
set -euo pipefail
cd "$(dirname "$0")/.."

ZIG="${ZIG:-zig}"
PYTHON="${PYTHON:-python3}"
OUT_DIR="dist"
BUILD_DIR=".build"

mkdir -p "$OUT_DIR" "$BUILD_DIR"

# 1. Embed the PowerShell media helper into the binary as a raw string literal.
"$PYTHON" - <<'PY'
src = open('src/win/smtc.ps1', encoding='utf-8').read()
assert ')YTLYSPLIT"' not in src, 'delimiter clash in smtc.ps1'
out = ('// Generated by scripts/build.sh - do not edit.\n'
       '#pragma once\nnamespace ytl {\nstatic const char kSmtcScript[] = R"YTLYSPLIT('
       + src + ')YTLYSPLIT";\n}\n')
open('.build/smtc_script.h', 'w', encoding='utf-8').write(out)
PY

# 2. Application icon + version info -> COFF .res object.
RES_ARG=""
if "$PYTHON" -c 'import PIL' 2>/dev/null; then
  "$PYTHON" scripts/make_icon.py "$BUILD_DIR"
  if "$ZIG" rc /i "$BUILD_DIR" src/win/app.rc "$BUILD_DIR/app.res"; then
    RES_ARG="$BUILD_DIR/app.res"
  else
    echo "warning: resource compilation failed, building without an icon"
  fi
else
  echo "note: Pillow not installed, building without an embedded icon"
fi

# 3. Cross compile.
"$ZIG" c++ -target x86_64-windows-gnu -std=c++17 -O2 \
  -municode -Wl,--subsystem,windows -Wl,--gc-sections \
  -fno-exceptions -fno-rtti -fno-strict-aliasing \
  -Wall -Wextra -Wno-unused-parameter -Wno-cast-function-type \
  -I"$BUILD_DIR" \
  -o "$OUT_DIR/YoutubeLyrics.exe" \
  src/core/core.cc \
  src/win/app.cc \
  src/win/render.cc \
  src/win/media.cc \
  src/win/lyrics.cc \
  $RES_ARG \
  -lgdiplus -lgdi32 -luser32 -lole32 -luuid -lshell32 -lshlwapi -ldwmapi \
  -lwinhttp -lcomdlg32 -ladvapi32

echo "built $OUT_DIR/YoutubeLyrics.exe"
ls -la "$OUT_DIR/YoutubeLyrics.exe"
